#!/usr/bin/env python3
"""Reusable 16x16 SNES glyphs. Edit assets/snes-pad.gif, then rerun make_assets.py.
Use --create to recreate the source sheet. No sibling-game dependencies.
"""
from pathlib import Path
import re
from PIL import Image, ImageDraw

NAMES = ('B', 'A', 'Y', 'X', 'L', 'R', 'START', 'SELECT', 'DPAD', 'UP', 'DOWN', 'LEFT', 'RIGHT')
COLORS = [(255, 0, 255), (28, 28, 40), (180, 180, 195), (255, 255, 255),
          (224, 64, 64), (56, 112, 224), (48, 168, 96), (248, 208, 48)]
LETTERS = {'A': ('010','101','111','101','101'), 'B': ('110','101','110','101','110'),
           'X': ('101','101','010','101','101'), 'Y': ('101','101','010','010','010'),
           'L': ('100','100','100','100','111'), 'R': ('110','101','110','101','101')}

def create(root):
    sheet = Image.new('P', (16 * len(NAMES), 16), 0)
    sheet.putpalette([v for rgb in COLORS for v in rgb] + [0] * (768 - len(COLORS) * 3))
    for i, name in enumerate(NAMES):
        tile = Image.new('P', (16, 16), 0)
        draw = ImageDraw.Draw(tile)
        if name in LETTERS:
            color = {'A': 4, 'B': 7, 'X': 5, 'Y': 6}.get(name, 2)
            if name in ('L', 'R'):
                draw.rounded_rectangle((2, 1, 13, 14), radius=3, fill=color, outline=1)
            else:
                draw.ellipse((2, 1, 13, 14), fill=color, outline=1)
            for y, row in enumerate(LETTERS[name]):
                for x, bit in enumerate(row):
                    if bit == '1': draw.rectangle((5+x*2, 3+y*2, 6+x*2, 4+y*2), fill=1 if name in ('B','L','R') else 3)
        elif name in ('START', 'SELECT'):
            draw.rounded_rectangle((2, 4, 13, 11), radius=3, fill=2, outline=1)
            if name == 'START': draw.polygon(((6,5),(10,8),(6,10)), fill=1)
            else:
                draw.line((5,6,10,6), fill=1)
                draw.line((5,9,10,9), fill=1)
        elif name == 'DPAD':
            draw.polygon(((6,1),(9,1),(9,5),(13,5),(13,10),(9,10),(9,14),(6,14),(6,10),(2,10),(2,5),(6,5)), fill=2, outline=1)
            draw.rectangle((6,6,9,9), fill=1)
        else:
            draw.polygon(((7,1),(12,6),(9,6),(9,13),(5,13),(5,6),(2,6)), fill=3, outline=1)
            tile = tile.rotate({'UP':0, 'DOWN':180, 'LEFT':90, 'RIGHT':270}[name])
        sheet.paste(tile, (i*16, 0))
    sheet.save(root/'assets/snes-pad.gif', optimize=False, transparency=0)

def install(root, base, font_tile=32):
    """Append only the glyph tiles; preserve every existing tile and palette index."""
    root = Path(root)
    sheet = Image.open(root/'assets/snes-pad.gif').convert('RGBA')
    assert sheet.size == (16 * len(NAMES), 16)
    image = Image.open(root/'assets/tileset.gif')
    assert image.mode == 'P' and image.width == 256
    assert max(image.tobytes()) < 248, 'reserved glyph palette overlaps game colors'
    assert base + len(NAMES) <= 256
    out = Image.new('P', (256, 16*((base+len(NAMES)+15)//16)), 0)
    palette = image.getpalette()[:]
    palette += [0] * (768-len(palette))
    # Use GIF alpha, independently of the transparent entry's marker color.
    glyph_colors = sorted({sheet.getpixel((x,y))[:3] for y in range(sheet.height)
                           for x in range(sheet.width) if sheet.getpixel((x,y))[3]})
    assert len(glyph_colors) <= 8, 'glyph sheet supports eight opaque colors'
    lookup = {}
    for index, rgb in enumerate(glyph_colors, 248):
        palette[index*3:index*3+3] = rgb
        lookup[rgb] = index
    # Match the game font: index zero stays transparent; opaque fonts keep
    # their existing background index and color (Courier/Lantern).
    background = image.getpixel(((font_tile % 16)*16, (font_tile // 16)*16))
    out.putpalette(palette)
    out.paste(image, (0,0))
    for i in range(len(NAMES)):
        for y in range(16):
            for x in range(16):
                pixel = sheet.getpixel((i*16+x,y))
                color = lookup[pixel[:3]] if pixel[3] else background
                out.putpixel((((base+i)%16)*16+x, ((base+i)//16)*16+y), color)
    out.save(root/'assets/tileset.gif', optimize=False)
    header = root/'src/gfx.h'
    if header.exists():
        text = re.sub(r'(#define TILE_COUNT\s+)\d+', r'\g<1>%d' % (base + len(NAMES)), header.read_text())
        header.write_text(text)
    lines = ['/* Generated by tools/snes_glyphs.py. Character strings for prompt concatenation. */',
             '#ifndef PAD_GLYPHS_H', '#define PAD_GLYPHS_H', "#define PAD_GLYPH_FIRST 'a'",
             '#define PAD_GLYPH_COUNT %d' % len(NAMES)]
    for i, name in enumerate(NAMES):
        lines += ['#define T_PAD_%s %d' % (name,base+i), '#define PAD_%s "%s"' % (name,chr(ord('a')+i))]
    lines += ['#endif', '']
    (root/'src/pad_glyphs.h').write_text('\n'.join(lines))
    # Tiled's metadata follows the sheet size; authored tile IDs never move.
    for tsx in (root/'assets').rglob('*.tsx'):
        text = tsx.read_text()
        if 'tileset.gif' not in text: continue
        text = re.sub(r'tilecount="\d+"', 'tilecount="%d"' % (out.width*out.height//256), text)
        text = re.sub(r'(<image[^>]*source="[^"]*tileset.gif"[^>]*height=")\d+', r'\g<1>%d' % out.height, text)
        tsx.write_text(text)
    preview = root/'screenshots/assets/tileset_preview.png'
    if preview.exists(): out.convert('RGB').resize((out.width*3,out.height*3), Image.Resampling.NEAREST).save(preview)
    print('SNES glyphs: tiles %d-%d; total tiles used: %d' % (base, base+len(NAMES)-1, base+len(NAMES)))

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--create', action='store_true', help='recreate the editable glyph source sheet')
    args = parser.parse_args()
    if args.create: create(Path(__file__).resolve().parents[1])
    else: parser.error('use --create, or regenerate the tileset with the game asset generator')
